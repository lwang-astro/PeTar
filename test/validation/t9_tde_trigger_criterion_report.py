def write_scenario() -> Path:
    """Regenerate the scenario JSON (deterministic, byte-identical output)."""
    scenario = build_scenario()
    out = REPO / SCENARIO_FILE
    out.write_text(json.dumps(scenario, indent=2) + "\n", encoding="utf-8")
    print(f"[T9] scenario written: {out} ({len(scenario['runs'])} runs, {len(scenario['checks'])} checks)")
    return out


